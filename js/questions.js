/* =========================================================
   组装成统一题库
   ========================================================= */
var QUESTIONS = (function () {
  var out = [], counter = {}, byContent = {};

  /* 1) 选择题 */
  RAW_CHOICE.forEach(function (r) {
    var kp = r[0];
    counter[kp] = (counter[kp] || 0) + 1;
    var q = {
      id: kp + '-' + counter[kp],
      type: 'choice',
      knowledge: kp,
      content: r[1],
      options: r[2],
      answer: r[3],
      why: r[4] || ''
    };
    out.push(q);
    if (!byContent[q.content]) byContent[q.content] = q;
  });

  function kpList(kp) {
    return out.filter(function (q) { return q.knowledge === kp && q.type === 'choice'; });
  }
  /* 不适合派生判断题的知识点
     三声连读 / 「一、不」变调这两个知识点本身是可以出判断题的：
     标成本调就是「读错了」，标成变调形式就是「读对了」，正好考孩子有没有掌握。
     （核验脚本对这两组只比声母韵母骨架，声调差异属设计预期） */
  var NO_JUDGE = {};

  var seq = 0;
  function push(q) { seq++; q.seq = seq; out.push(q); }

  KNOWLEDGE_POINTS.forEach(function (kp) {
    var qs = kpList(kp.id);

    /* 2) 听音辨音：只放声音不给字，选听到的拼音（复用选择题语音） */
    if (qs.length >= 2) {
      var base = qs[1 % qs.length];
      push({
        id: 'L-' + base.id, type: 'listen', knowledge: kp.id,
        content: base.content, options: base.options, answer: base.answer,
        why: base.why, audioId: base.id, hideWord: true
      });
    }

    /* 3) 判断对错：给字和一个拼音，判断读得对不对（含拼写陷阱） */
    if (!NO_JUDGE[kp.id] && qs.length >= 2) {
      for (var k = 0; k < 2; k++) {
        var b = qs[(k * 3 + 1) % qs.length];
        var wrong = (k === 0);
        var pinyin = wrong ? b.options[(b.answer + 1) % b.options.length] : b.options[b.answer];
        push({
          id: 'J' + k + '-' + b.id, type: 'judge', knowledge: kp.id,
          content: b.content, judgePinyin: pinyin, judgeOk: !wrong,
          why: b.content + ' 读 ' + b.options[b.answer] + '，' + b.why,
          audioId: b.id
        });
      }
    }

    /* 4) 连线配对：4 组 汉字 ↔ 拼音
       注意：不能用「固定隔一个取一个」的取法 —— 有些知识点里会出现同音字
       （如 ye_yue_yuan 的「圆 yuán / 员 yuán」），一旦撞上重复就要继续往下找，
       否则凑不满 4 对就整道题都不生成。 */
    var pairs = [], usedP = {}, usedC = {};
    for (var m = 0; m < qs.length && pairs.length < 4; m++) {
      var q2 = qs[m], py = q2.options[q2.answer];
      if (usedP[py] || usedC[q2.content]) continue;
      usedP[py] = 1;
      usedC[q2.content] = 1;
      pairs.push([q2.content, py]);
    }
    if (pairs.length === 4) {
      push({
        id: 'M-' + kp.id, type: 'match', knowledge: kp.id,
        content: pairs[0][0], pairs: pairs, noAudio: true,
        why: '连一连：把字和它的读音配成对'
      });
    }
  });

  /* 5) 声母填空 */
  RAW_FILL.forEach(function (r, i) {
    var base = byContent[r[1]];
    push({
      id: 'F-' + r[0] + '-' + (i + 1), type: 'fill', knowledge: r[0],
      content: r[1], display: r[2], options: r[3], answer: r[4],
      why: r[5], audioId: base ? base.id : undefined
    });
  });

  /* 6) 拼读积木 */
  RAW_SPELL.forEach(function (r, i) {
    var base = byContent[r[1]];
    push({
      id: 'S-' + r[0] + '-' + (i + 1), type: 'spell', knowledge: r[0],
      content: r[1], tiles: r[2], extraTiles: r[3],
      why: r[4], audioId: base ? base.id : undefined
    });
  });

  return out;
})();

